def is_valid_category(
    category_type: str,
    label: str,
) -> bool:

    if category_type == "other":
        return label == OTHER_CATEGORY

    if category_type == "agent":
        return label in AGENT_CATEGORIES

    if category_type == "special":
        return label in SPECIAL_CATEGORIES

    return False
